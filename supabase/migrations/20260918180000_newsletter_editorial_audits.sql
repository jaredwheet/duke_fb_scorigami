create or replace function public.reject_newsletter_editorial_audit_mutation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  raise exception 'newsletter editorial audit rows are append-only';
end;
$$;

create or replace function public.validate_newsletter_editorial_audit_linkage()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  delivery_issue_id bigint;
  delivery_attempts integer;
begin
  if new.delivery_id is null then return new; end if;
  select issue_id, attempts into delivery_issue_id, delivery_attempts
  from public.newsletter_deliveries where id = new.delivery_id;
  if delivery_issue_id is null or delivery_issue_id <> new.issue_id then
    raise exception 'newsletter editorial audit delivery does not belong to issue';
  end if;
  if new.attempt <> coalesce(delivery_attempts, 0) then
    raise exception 'newsletter editorial audit attempt does not match delivery attempt';
  end if;
  return new;
end;
$$;

drop trigger if exists newsletter_editorial_audits_validate_linkage on public.newsletter_editorial_audits;
