create or replace function public.newsletter_editorial_audit_sections_bounded(p_value jsonb)
returns boolean
language plpgsql
immutable
as $$
declare
  entry record;
  reason jsonb;
begin
  if jsonb_typeof(p_value) <> 'object'
    or (select count(*) from jsonb_object_keys(p_value)) > 5
    or octet_length(p_value::text) > 16384 then
    return false;
  end if;
  for entry in select key, value from jsonb_each(p_value) loop
    if char_length(entry.key) > 64
      or jsonb_typeof(entry.value) <> 'object'
      or jsonb_typeof(entry.value->'disposition') <> 'string'
      or char_length(entry.value->>'disposition') > 32
      or jsonb_typeof(entry.value->'rejectionReasons') <> 'array'
      or jsonb_array_length(entry.value->'rejectionReasons') > 16 then
      return false;
    end if;
    for reason in select value from jsonb_array_elements(entry.value->'rejectionReasons') loop
      if jsonb_typeof(reason) <> 'string' or char_length(reason #>> '{}') > 128 then
        return false;
      end if;
    end loop;
  end loop;
  return true;
end;
$$;

create or replace function public.newsletter_editorial_audit_warnings_bounded(p_value jsonb)
returns boolean
language plpgsql
immutable
as $$
declare
  warning jsonb;
begin
  if jsonb_typeof(p_value) <> 'array'
    or jsonb_array_length(p_value) > 8
    or octet_length(p_value::text) > 2048 then
    return false;
  end if;
  for warning in select value from jsonb_array_elements(p_value) loop
    if jsonb_typeof(warning) <> 'string' or char_length(warning #>> '{}') > 128 then
      return false;
    end if;
  end loop;
  return true;
end;
$$;

create table if not exists public.newsletter_editorial_audits (
  id bigint generated by default as identity primary key,
  issue_id bigint not null references public.newsletter_issues(id) on delete cascade,
  delivery_id bigint not null references public.newsletter_deliveries(id) on delete cascade,
  attempt integer not null default 1 check (attempt between 1 and 1000),
  mode text not null check (char_length(mode) between 1 and 64),
  provider text check (provider is null or char_length(provider) between 1 and 64),
  model text check (model is null or char_length(model) between 1 and 128),
  packet_version text not null check (char_length(packet_version) between 1 and 64),
  schema_version text not null check (char_length(schema_version) between 1 and 64),
  validator_version text not null check (char_length(validator_version) between 1 and 64),
  fallback_version text not null check (char_length(fallback_version) between 1 and 64),
  section_results jsonb not null,
  discovery_warnings jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

